"""Experiment tracking for simulation runs.

Every run is a directory under runs/ holding everything needed to audit or reproduce it:

    runs/<YYYYMMDD-HHMMSS>-<name>/
        config.yaml     resolved parameters with their source notes, plus overrides
        meta.json       git commit, dirty flag, host, timings, group, tags
        metrics.json    scalar results (the numbers a reviewer compares)
        series.csv.gz   time series (one column per channel)
        *.png           figures

`python -m cvtsim.runs` rebuilds runs/INDEX.md, a table of all runs and their metrics.
"""
import datetime as _dt
import gzip
import json
import pathlib
import platform
import subprocess
import time

import numpy as np
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1] / "runs"


def _git(*args):
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              cwd=ROOT.parent, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


class Run:
    def __init__(self, name, raw_params, overrides=None, group="", tags=()):
        stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
        self.dir = ROOT / f"{stamp}-{name.replace(' ', '_').replace('/', '-')}"
        self.dir.mkdir(parents=True, exist_ok=False)
        self.metrics = {}
        self._t0 = time.time()
        self.meta = dict(name=name, group=group, tags=list(tags), started=stamp,
                         commit=_git("rev-parse", "HEAD"), dirty=bool(_git("status", "--porcelain", "--", ".", ":!runs")),
                         python=platform.python_version(), host=platform.node())
        with open(self.dir / "config.yaml", "w") as f:
            yaml.safe_dump(dict(overrides=overrides or {}, parameters=raw_params), f, sort_keys=False)

    def log(self, **metrics):
        self.metrics.update({k: float(v) for k, v in metrics.items()})

    def series(self, columns, data):
        with gzip.open(self.dir / "series.csv.gz", "wt") as f:
            np.savetxt(f, data, delimiter=",", header=",".join(columns), comments="", fmt="%.9g")

    def figure(self, fig, name):
        fig.savefig(self.dir / f"{name}.png")

    def finish(self):
        self.meta["wall_s"] = round(time.time() - self._t0, 1)
        (self.dir / "metrics.json").write_text(json.dumps(self.metrics, indent=2))
        (self.dir / "meta.json").write_text(json.dumps(self.meta, indent=2))
        return self.dir


def load_all():
    runs = []
    for d in sorted(ROOT.glob("*/metrics.json")):
        runs.append(dict(dir=d.parent, metrics=json.loads(d.read_text()),
                         meta=json.loads((d.parent / "meta.json").read_text())))
    return runs


def write_index():
    runs = load_all()
    keys = sorted({k for r in runs for k in r["metrics"]})
    lines = ["# Runs", "", "Generated by `python -m cvtsim.runs`. One row per tracked run.", "",
             "| run | group | commit | " + " | ".join(keys) + " |",
             "|---|---|---|" + "---|" * len(keys)]
    for r in runs:
        m, meta = r["metrics"], r["meta"]
        commit = meta["commit"][:7] + ("*" if meta["dirty"] else "")
        cells = [f"{m[k]:.4g}" if k in m else "" for k in keys]
        lines.append(f"| [{r['dir'].name}]({r['dir'].name}/) | {meta['group']} | {commit} | "
                     + " | ".join(cells) + " |")
    (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    write_index()
